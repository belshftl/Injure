using System.Diagnostics;
using System.Numerics;
using Injure.Assets;
using Injure.Draw.PixelConv;
using Injure.DevAnalyzers.Attributes;
using Injure.Gpu;

namespace Injure.Draw;

/// <summary>
/// Storage formats supported by <see cref="Texture2d"/>. The number is the total bits per texel.
/// </summary>
/// <remarks>
/// <para>
/// There are no sRGB formats, since <see cref="Canvas"/> takes texels as stored; color textures
/// hold sRGB-encoded values in plain unorm formats.
/// </para>
/// <para>
/// The <see langword="default"/> value is invalid.
/// </para>
/// </remarks>
[ClosedEnum(DefaultIsInvalid = true)]
public readonly partial struct Texture2dFormat {
	/// <summary>Raw switch tag for <see cref="Texture2dFormat"/>.</summary>
	public enum Case {
		/// <summary>
		/// One 8-bit unsigned normalized channel (R), e.g. for coverage masks.
		/// </summary>
		R8Unorm = 1,

		/// <summary>
		/// Two 8-bit unsigned normalized channels (RG).
		/// </summary>
		Rg16Unorm,

		/// <summary>
		/// Four 8-bit unsigned normalized channels (RGBA).
		/// </summary>
		Rgba32Unorm,

		/// <summary>
		/// Four 8-bit unsigned normalized channels, stored in BGRA order.
		/// </summary>
		Bgra32Unorm,
	}
}

/// <summary>
/// How <see cref="Texture2d"/> computes its mip levels, each from the level above it.
/// </summary>
/// <remarks>
/// The <see langword="default"/> value is invalid.
/// </remarks>
[ClosedEnum(DefaultIsInvalid = true)]
public readonly partial struct Texture2dMipFilter {
	/// <summary>Raw switch tag for <see cref="Texture2dMipFilter"/>.</summary>
	public enum Case {
		/// <summary>
		/// For sRGB-encoded color with straight alpha, i.e. what <see cref="Canvas"/> draws with
		/// <see cref="CanvasMaterials.Color"/>. Averages in linear light, weighted by alpha, so
		/// transparent texels don't darken the edges of visible ones.
		/// </summary>
		Color = 1,

		/// <summary>
		/// Averages the stored values as they are. For data where that's meaningful, e.g. coverage masks
		/// (<see cref="CanvasMaterials.Rmask"/>) and distance fields.
		/// </summary>
		Raw,
	}
}

/// <summary>
/// High-level wrapper for a 2D color texture.
/// </summary>
/// <remarks>
/// <para>
/// Intentionally narrower than <see cref="GpuTexture"/>; always represents a single-layer,
/// non-multisampled, sampleable 2D color or mask texture with a default view. It doesn't have a
/// sampler; how <see cref="Canvas"/> samples it is draw state (<see cref="TexSampling"/>).
/// </para>
/// <para>
/// It has either a single mip level, or a full mip chain (down to 1x1) if created with
/// <see cref="Texture2dCreateParams.Mips"/>. Uploads only write the base level; the other levels
/// are computed from it on the GPU, the first time the texture is drawn after an upload, or by
/// <see cref="GenerateMips()"/>.
/// </para>
/// <para>
/// A texture loaded through an <see cref="AssetStore"/> is owned by the store until the store
/// reclaims it (see <see cref="IsAssetStoreOwned"/>), and disposing it before that throws. Once
/// reclaimed, members that use the texture throw <see cref="ObjectDisposedException"/>, like after
/// any other disposal.
/// </para>
/// </remarks>
public sealed class Texture2d : IAssetStoreDisposable {
	private readonly GpuDevice device;
	private readonly GpuTexture texture;
	private GpuBindGroup? bindGroup = null;
	private int mipsDirty = 0;
	private int disposed = 0;
	private AssetStoreCustody? custody;

	internal GpuTexture Texture {
		get {
			chk();
			return texture;
		}
	}
	// view-only, for Canvas, which binds the sampler separately
	internal GpuBindGroupRef BindGroup {
		get {
			chk();
			flushMips();
			return (bindGroup ??= DrawDeviceResources.For(device).CreateColorTexture2dViewBindGroup(Texture.DefaultView)).AsRef();
		}
	}

	/// <summary>
	/// Returns the underlying <see cref="GpuTexture"/>, which stops being usable once this texture is
	/// disposed.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Out-of-date mip levels aren't regenerated by this call; use <see cref="GenerateMips()"/> before
	/// sampling them.
	/// </para>
	/// <para>
	/// See <c>docs/conventions/dangerous-get-create.md</c>.
	/// </para>
	/// </remarks>
	public GpuTextureRef DangerousGetGpuTexture() => Texture.AsRef();

	/// <summary>
	/// Width of the texture in texels.
	/// </summary>
	public uint Width => Texture.Width;

	/// <summary>
	/// Height of the texture in texels.
	/// </summary>
	public uint Height => Texture.Height;

	/// <summary>
	/// High-level storage format of the texture.
	/// </summary>
	public Texture2dFormat Format { get; }

	/// <summary>
	/// How the mip levels are computed, or <see langword="null"/> if the texture has a single mip
	/// level.
	/// </summary>
	public Texture2dMipFilter? MipFilter { get; }

	/// <summary>
	/// Number of mip levels, including the base level.
	/// </summary>
	public uint MipLevelCount => Texture.MipLevelCount;

	/// <summary>
	/// The pixel format that
	/// <see cref="Upload(ReadOnlySpan{byte}, int, PixelFormat, PixelConvertOptions)"/> converts
	/// uploaded data to.
	/// </summary>
	public PixelFormat UploadPixelFormat { get; }

	/// <summary>
	/// Creates an empty <see cref="Texture2d"/> with the given size and
	/// <see cref="Texture2dFormat.Rgba32Unorm"/>.
	/// </summary>
	/// <param name="device">Device to create the texture on.</param>
	/// <param name="width">Width in texels.</param>
	/// <param name="height">Height in texels.</param>
	/// <inheritdoc cref="Texture2d(GpuDevice, in Texture2dCreateParams)" path="/exception"/>
	public Texture2d(GpuDevice device, uint width, uint height)
		: this(device, new Texture2dCreateParams(width, height)) {
	}

	/// <summary>
	/// Creates an empty <see cref="Texture2d"/> with the given size and format.
	/// </summary>
	/// <param name="device">Device to create the texture on.</param>
	/// <param name="width">Width in texels.</param>
	/// <param name="height">Height in texels.</param>
	/// <param name="format">Storage format.</param>
	/// <inheritdoc cref="Texture2d(GpuDevice, in Texture2dCreateParams)" path="/exception"/>
	public Texture2d(GpuDevice device, uint width, uint height, Texture2dFormat format)
		: this(device, new Texture2dCreateParams(width, height, format)) {
	}

	/// <summary>
	/// Creates an empty <see cref="Texture2d"/>.
	/// </summary>
	/// <param name="device">Device to create the texture on.</param>
	/// <param name="params">Size, format, and mip levels.</param>
	/// <exception cref="ArgumentNullException">
	/// Thrown if <paramref name="device"/> is <see langword="null"/>.
	/// </exception>
	/// <exception cref="ArgumentOutOfRangeException">
	/// Thrown if the width or height is 0.
	/// </exception>
	/// <exception cref="ArgumentException">
	/// Thrown if the format or mip filter is the invalid <see langword="default"/> value.
	/// </exception>
	public Texture2d(GpuDevice device, in Texture2dCreateParams @params) {
		ArgumentNullException.ThrowIfNull(device);
		ArgumentOutOfRangeException.ThrowIfZero(@params.Width);
		ArgumentOutOfRangeException.ThrowIfZero(@params.Height);
		if (@params.Format == default(Texture2dFormat))
			throw new ArgumentException("format must not be the default value", nameof(@params));
		if (@params.Mips == default(Texture2dMipFilter))
			throw new ArgumentException("mip filter must not be the default value", nameof(@params));

		this.device = device;
		Texture2dFormat fmt = @params.Format ?? Texture2dFormat.Rgba32Unorm;
		Format = fmt;
		UploadPixelFormat = getUploadPixelFormat(fmt);
		MipFilter = @params.Mips;

		texture = device.CreateTexture(
			new GpuTextureCreateParams(
				Width: @params.Width,
				Height: @params.Height,
				DepthOrArrayLayers: 1,
				MipLevelCount: @params.Mips is null ? 1 : fullChainLength(@params.Width, @params.Height),
				SampleCount: 1,
				Dimension: TextureDimension.Dimension2d,
				Format: getTextureFormat(fmt),
				// mip levels are rendered from the level above
				Usage: TextureUsage.TextureBinding | TextureUsage.CopyDst | (@params.Mips is null ? TextureUsage.None : TextureUsage.RenderAttachment)
			)
		);
	}

	// down to 1x1
	private static uint fullChainLength(uint width, uint height) => (uint)BitOperations.Log2(Math.Max(width, height)) + 1;

	/// <summary>
	/// Uploads pixel data to the entire texture.
	/// </summary>
	/// <param name="src">Source pixel data.</param>
	/// <param name="srcStride">Stride of <paramref name="src"/> in bytes (not pixels).</param>
	/// <param name="srcFmt">Pixel format of <paramref name="src"/>.</param>
	/// <param name="opts">Pixel conversion options.</param>
	/// <inheritdoc cref="Upload(int, int, ReadOnlySpan{byte}, int, PixelFormat, int, int, PixelConvertOptions)" path="/exception"/>
	public void Upload(ReadOnlySpan<byte> src, int srcStride, PixelFormat srcFmt, PixelConvertOptions opts = default) =>
		Upload(0, 0, src, srcStride, srcFmt, checked((int)Width), checked((int)Height), opts);

	/// <summary>
	/// Uploads pixel data to a sub-rectangle of the texture.
	/// </summary>
	/// <param name="x">Destination X offset in texels.</param>
	/// <param name="y">Destination Y offset in texels.</param>
	/// <param name="src">Source pixel data.</param>
	/// <param name="srcStride">Stride of <paramref name="src"/> in bytes (not pixels).</param>
	/// <param name="srcFmt">Pixel format of <paramref name="src"/>.</param>
	/// <param name="width">Width of the upload rectangle in texels.</param>
	/// <param name="height">Height of the upload rectangle in texels.</param>
	/// <param name="opts">Pixel conversion options.</param>
	/// <exception cref="ArgumentOutOfRangeException">
	/// Thrown if <paramref name="x"/> or <paramref name="y"/> is negative, or
	/// <paramref name="srcStride"/>, <paramref name="width"/>, or <paramref name="height"/> is
	/// negative or zero.
	/// </exception>
	/// <exception cref="ArgumentException">
	/// Thrown if the rectangle extends past the texture, if <paramref name="srcStride"/> is smaller
	/// than a tightly packed row of <paramref name="width"/> pixels, or if <paramref name="src"/> is
	/// too small for the rectangle.
	/// </exception>
	/// <exception cref="InvalidOperationException">
	/// Thrown if converting from <paramref name="srcFmt"/> would narrow, drop alpha, or drop color
	/// channels without the corresponding <see cref="ConversionFlags"/> in <paramref name="opts"/>.
	/// </exception>
	/// <exception cref="ObjectDisposedException">
	/// Thrown if the texture has been disposed.
	/// </exception>
	public void Upload(int x, int y, ReadOnlySpan<byte> src, int srcStride, PixelFormat srcFmt, int width, int height, PixelConvertOptions opts = default) {
		chk();
		ArgumentOutOfRangeException.ThrowIfNegative(x);
		ArgumentOutOfRangeException.ThrowIfNegative(y);
		ArgumentOutOfRangeException.ThrowIfNegativeOrZero(srcStride);
		ArgumentOutOfRangeException.ThrowIfNegativeOrZero(width);
		ArgumentOutOfRangeException.ThrowIfNegativeOrZero(height);
		if ((uint)x + (uint)width > Width || (uint)y + (uint)height > Height)
			throw new ArgumentException("upload rectangle is out of bounds of the texture");

		byte[] converted = PixelConverter.Convert(src, srcStride, srcFmt, UploadPixelFormat, out int dstStride, width, height, opts);
		device.WriteToTexture(
			texture,
			new GpuTextureRegion(
				X: (uint)x,
				Y: (uint)y,
				Z: 0,
				Width: (uint)width,
				Height: (uint)height,
				DepthOrArrayLayers: 1,
				MipLevel: 0,
				Aspect: TextureAspect.All
			),
			converted,
			new GpuTextureLayout(
				Offset: 0,
				BytesPerRow: (uint)dstStride,
				RowsPerImage: (uint)height
			)
		);
		if (MipFilter is not null)
			Volatile.Write(ref mipsDirty, 1);
	}

	/// <summary>
	/// Computes the mip levels below the base level from it now, if they're out of date, rather than
	/// the next time the texture is drawn.
	/// </summary>
	/// <remarks>
	/// The levels are out of date after an upload. Generation is submitted to the device's queue right
	/// away, so it's ordered after earlier uploads and before command buffers submitted later.
	/// </remarks>
	/// <exception cref="InvalidOperationException">
	/// Thrown if the texture has a single mip level.
	/// </exception>
	/// <exception cref="ObjectDisposedException">
	/// Thrown if the texture has been disposed.
	/// </exception>
	public void GenerateMips() {
		chk();
		if (MipFilter is null)
			throw new InvalidOperationException("texture has a single mip level");
		flushMips();
	}

	private void flushMips() {
		if (MipFilter is Texture2dMipFilter filter && Interlocked.Exchange(ref mipsDirty, 0) != 0)
			Texture2dMipGenerator.For(device).Generate(texture, filter);
	}

	/// <inheritdoc/>
	public bool IsAssetStoreOwned => custody is { IsReleased: false };

	void IAssetStoreValue.AttachCustody(AssetStoreCustody custody) => this.custody = custody;

	/// <summary>
	/// Releases the owned GPU resources.
	/// </summary>
	/// <exception cref="InvalidOperationException">
	/// Thrown if an asset store owns this texture; see <see cref="IsAssetStoreOwned"/>.
	/// </exception>
	public void Dispose() {
		custody?.ThrowIfHeld(this);
		if (Interlocked.Exchange(ref disposed, 1) != 0)
			return;

		bindGroup?.Dispose();
		texture.Dispose();
	}

	private static TextureFormat getTextureFormat(Texture2dFormat fmt) => fmt.Tag switch {
		Texture2dFormat.Case.R8Unorm => TextureFormat.R8Unorm,
		Texture2dFormat.Case.Rg16Unorm => TextureFormat.Rg8Unorm,
		Texture2dFormat.Case.Rgba32Unorm => TextureFormat.Rgba8Unorm,
		Texture2dFormat.Case.Bgra32Unorm => TextureFormat.Bgra8Unorm,
		_ => throw new UnreachableException(),
	};

	private static PixelFormat getUploadPixelFormat(Texture2dFormat fmt) => fmt.Tag switch {
		Texture2dFormat.Case.R8Unorm => PixelFormat.R8_Unorm,
		Texture2dFormat.Case.Rg16Unorm => PixelFormat.Rg16_Unorm,
		Texture2dFormat.Case.Rgba32Unorm => PixelFormat.Rgba32_Unorm,
		Texture2dFormat.Case.Bgra32Unorm => PixelFormat.Bgra32_Unorm,
		_ => throw new UnreachableException(),
	};

	private void chk() {
		if (Volatile.Read(ref disposed) == 0)
			return;
		if (custody is not null)
			throw new ObjectDisposedException(nameof(Texture2d), $"this texture is {custody}, which the asset store reclaimed");
		throw new ObjectDisposedException(nameof(Texture2d));
	}
}

/// <summary>
/// Parameters used to create a <see cref="Texture2d"/>.
/// </summary>
/// <param name="Width">Texture width in texels.</param>
/// <param name="Height">Texture height in texels.</param>
/// <param name="Format">
/// Storage format, or <see langword="null"/> for <see cref="Texture2dFormat.Rgba32Unorm"/>.
/// </param>
/// <param name="Mips">
/// How to compute a full mip chain, or <see langword="null"/> for a single mip level. Mips cost
/// about a third more memory, and keep textures drawn smaller than about half their size from
/// aliasing with <see cref="TexFilter.Linear"/>; see <see cref="TexSampling"/>.
/// </param>
/// <remarks>
/// The <see langword="default"/> value is invalid, since its width and height are 0 and its
/// <see cref="Format"/> is invalid.
/// </remarks>
public readonly record struct Texture2dCreateParams(
	uint Width,
	uint Height,
	Texture2dFormat? Format = null,
	Texture2dMipFilter? Mips = null
);
